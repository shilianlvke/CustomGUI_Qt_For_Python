from __future__ import annotations

import ast
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS_DIR = ROOT / "Docs"
PACKAGES = ("customgui.appcore", "customgui.guis", "customgui.guicore", "Apps")


@dataclass(frozen=True)
class ApiItem:
    kind: str
    name: str
    lineno: int


def _iter_python_files() -> Iterable[Path]:
    for package in PACKAGES:
        base = ROOT / package
        if not base.exists():
            continue
        for path in sorted(base.rglob("*.py")):
            if "__pycache__" in path.parts:
                continue
            yield path


def _module_name(path: Path) -> str:
    rel = path.relative_to(ROOT).with_suffix("")
    parts = list(rel.parts)
    # __init__.py 表示为包名而非 "xxx.__init__"
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _collect_api(path: Path) -> list[ApiItem]:
    source = path.read_text(encoding="utf-8")
    tree = ast.parse(source)
    items: list[ApiItem] = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            items.append(ApiItem(kind="class", name=node.name, lineno=node.lineno))
        if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
            items.append(ApiItem(kind="function", name=node.name, lineno=node.lineno))
    return items


def _top_package(module: str | None) -> str | None:
    if not module:
        return None
    head = module.split(".", 1)[0]
    if head in PACKAGES:
        return head
    return None


def _collect_edges(path: Path) -> set[tuple[str, str]]:
    source = path.read_text(encoding="utf-8")
    tree = ast.parse(source)
    current = path.relative_to(ROOT).parts[0]
    edges: set[tuple[str, str]] = set()

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                target = _top_package(alias.name)
                if target and target != current:
                    edges.add((current, target))
        elif isinstance(node, ast.ImportFrom):
            target = _top_package(node.module)
            if target and target != current:
                edges.add((current, target))
    return edges


def generate_architecture_md(edges: set[tuple[str, str]]) -> str:
    edge_lines = []
    for source, target in sorted(edges):
        edge_lines.append(f"    {source} --> {target}")

    edge_block = "\n".join(edge_lines) if edge_lines else "    Apps --> customgui.appcore"

    return f"""# Architecture

This file is auto-generated by scripts/generate_docs.py.

## High-Level Layers

- customgui.appcore: app context, config loading, theme/language/telemetry modules, plugin protocol
- customgui.guis: base window framework, welcome page, app loader, language service
- customgui.guicore: reusable UI components and style system
- Apps: self-contained app modules (discovered and mounted by the base)

## Dependency Graph

```mermaid
flowchart LR
    customgui.appcore[customgui.appcore]
    customgui.guis[customgui.guis]
    customgui.guicore[customgui.guicore]
    Apps[Apps]

{edge_block}
```
"""


