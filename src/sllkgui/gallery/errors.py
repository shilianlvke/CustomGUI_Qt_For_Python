"""Gallery 稳定错误码与异常类型。

所有跨模块可见的失败都收敛成 :class:`GalleryError`：CLI 直接打印
``code: message``，UI 用 ``code`` 做本地化与操作建议，测试按 ``code`` 断言。
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

#: 清单与插件校验
PLUGIN_MANIFEST_INVALID = "PLUGIN_MANIFEST_INVALID"
PLUGIN_ID_INVALID = "PLUGIN_ID_INVALID"
PLUGIN_VERSION_INVALID = "PLUGIN_VERSION_INVALID"
PLUGIN_SCHEMA_UNSUPPORTED = "PLUGIN_SCHEMA_UNSUPPORTED"
PLUGIN_API_UNSUPPORTED = "PLUGIN_API_UNSUPPORTED"
PLUGIN_ENTRY_MISSING = "PLUGIN_ENTRY_MISSING"
PLUGIN_SURFACE_EMPTY = "PLUGIN_SURFACE_EMPTY"
PLUGIN_SURFACE_DUPLICATE = "PLUGIN_SURFACE_DUPLICATE"
PLUGIN_SURFACE_FACTORY_MISSING = "PLUGIN_SURFACE_FACTORY_MISSING"
PLUGIN_PATH_ESCAPE = "PLUGIN_PATH_ESCAPE"
PLUGIN_REQUIRES_UNSATISFIED = "PLUGIN_REQUIRES_UNSATISFIED"

#: 安装与依赖
PLUGIN_ALREADY_INSTALLED = "PLUGIN_ALREADY_INSTALLED"
PLUGIN_NOT_INSTALLED = "PLUGIN_NOT_INSTALLED"
PLUGIN_DEPENDENCY_MISSING = "PLUGIN_DEPENDENCY_MISSING"
PLUGIN_DEPENDENCY_CONFLICT = "PLUGIN_DEPENDENCY_CONFLICT"
PLUGIN_DEPENDENCY_CYCLE = "PLUGIN_DEPENDENCY_CYCLE"
PLUGIN_DEPENDENCY_DISABLED = "PLUGIN_DEPENDENCY_DISABLED"
PLUGIN_SOURCE_CONFLICT = "PLUGIN_SOURCE_CONFLICT"
PLUGIN_REMOVE_REQUIRED_BY = "PLUGIN_REMOVE_REQUIRED_BY"
PLUGIN_COMMIT_MISMATCH = "PLUGIN_COMMIT_MISMATCH"
PLUGIN_HASH_MISMATCH = "PLUGIN_HASH_MISMATCH"
PLUGIN_VERSION_NOT_FOUND = "PLUGIN_VERSION_NOT_FOUND"
PLUGIN_LOAD_FAILED = "PLUGIN_LOAD_FAILED"

#: 源
SOURCE_INVALID = "SOURCE_INVALID"
SOURCE_DUPLICATE = "SOURCE_DUPLICATE"
SOURCE_NOT_FOUND = "SOURCE_NOT_FOUND"
SOURCE_REFRESH_FAILED = "SOURCE_REFRESH_FAILED"

#: Git
GIT_UNAVAILABLE = "GIT_UNAVAILABLE"
GIT_URL_REJECTED = "GIT_URL_REJECTED"
GIT_TIMEOUT = "GIT_TIMEOUT"


@dataclass
class GalleryError(Exception):
    """Gallery 运行时的统一异常。

    ``params`` 用于 UI 本地化插值，``detail`` 放技术细节（只进日志，不直接
    展示给用户）。
    """

    code: str
    message: str
    detail: str = ""
    params: dict[str, Any] = field(default_factory=dict)

    def __str__(self) -> str:  # pragma: no cover - 纯展示
        return f"{self.code}: {self.message}"


__all__ = [name for name in globals() if name.isupper()] + ["GalleryError"]
